// Function to get random jobs from the list
export const getRandomJobs = (count: number): Job[] => {
  const jobsCopy = [...pythonJobs]

  for (let i = jobsCopy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[jobsCopy[i], jobsCopy[j]] = [jobsCopy[j], jobsCopy[i]]
  }
  return jobsCopy.slice(0, count)
}
